"""Inspect source alpha components and emit atlas metadata; never changes image pixels."""
from collections import deque
from pathlib import Path
import json
from PIL import Image

root=Path(__file__).resolve().parents[1]
result={}
for kind in ('inj','dummy'):
    im=Image.open(root/f'assets/{kind}-sprites-v2.png').convert('RGBA')
    w,h=im.size
    alpha=im.getchannel('A').tobytes()
    visited=bytearray(w*h)
    components=[]
    for seed,value in enumerate(alpha):
        if value<32 or visited[seed]: continue
        visited[seed]=1
        todo=deque([seed]);count=0;left=w;top=h;right=bottom=0;points=[]
        while todo:
            i=todo.popleft();y,x=divmod(i,w);count+=1
            left=min(left,x);right=max(right,x);top=min(top,y);bottom=max(bottom,y);points.append((x,y))
            for j in (i-1 if x else -1,i+1 if x<w-1 else -1,i-w if y else -1,i+w if y<h-1 else -1):
                if j>=0 and not visited[j] and alpha[j]>=32:
                    visited[j]=1;todo.append(j)
        if count>2500:
            feet=[x for x,y in points if y>bottom-(bottom-top)*.07]
            components.append({'x':left,'y':top,'w':right-left+1,'h':bottom-top+1,'footX':round(sum(feet)/len(feet),2),'area':count})
    if len(components)!=12:raise RuntimeError(f'{kind}: expected 12 sprites, found {len(components)}')
    components.sort(key=lambda b:b['y']+b['h']/2)
    ordered=[]
    for row in range(3):ordered.extend(sorted(components[row*4:row*4+4],key=lambda b:b['x']+b['w']/2))
    neutral_root=ordered[0]['footX']
    for index,b in enumerate(ordered):
        # Planted feet anchor standing poses. Low/airborne poses retain their column's neutral root.
        column=index%4
        anchor=b['footX'] if index not in (7,8,9,10) else neutral_root+column*w/4
        b['anchorX']=round(anchor-b['x'],2)
        b['anchorY']=b['h']
        del b['footX'];del b['area']
    # Airborne art is positioned around the torso, not its extended flying-kick boot.
    ordered[8]['anchorY']=round(ordered[0]['h']*.72,2)
    result[kind]={'width':w,'height':h,'neutralHeight':ordered[0]['h'],'frames':ordered}
    print(kind,json.dumps(result[kind],indent=2))
(root/'assets/fighter-frames.js').write_text('/* Source alpha bounds. Generated by tools/inspect-sprites.py; no image pixels modified. */\nwindow.InjSpriteFrames='+json.dumps(result,separators=(',',':'))+';\n')
