/* Held directions, buffered presses and committed actions share keyboard/touch rules. */
module.exports = async function verifyInput(page, check) {
  const results = await page.evaluate(() => {
    const a = INJ, out = {};
    const play = a.Sfx.play;
    a.Sfx.play = () => {};
    function setup(key) {
      a.game.round = 0;
      a.resetRound();
      a.game.state = 'fight';
      a.game.paused = false;
      a.dummy.aiT = 999;
      a.player.x = 160;
      a.dummy.x = 380;
      if (key) a.startAttack(a.player, key);
    }
    function endTime(f) { return f.atk.def.startup + f.atk.def.active + f.atk.def.recovery; }
    try {
      setup('roundhouse');
      const kick = a.player.atk;
      a.input.left = 1;
      a.controlPlayer(a.player, a.dummy, 0.1);
      out.groundKickCommitsWithoutSliding = a.player.atk === kick && a.player.x === 160 && a.player.grounded;
      a.controlPlayer(a.player, a.dummy, 0.35);
      out.heldLeftMovesDuringRemainingRecoveryFrame = !a.player.atk && Math.abs(a.player.x - (160 - 96 * 0.02)) < 0.001;
      setup('roundhouse');
      a.player.atk.t = endTime(a.player) - 0.12;
      a.queueAction('jump');
      a.controlPlayer(a.player, a.dummy, 0.12);
      out.tappedJumpStartsOnFirstLegalFrame = !a.player.grounded && a.player.vy < 0 && !a.player.atk;
      setup('roundhouse');
      a.player.atk.t = endTime(a.player) - 0.01;
      a.queueAction('jump');
      a.game.inputTime = 0.2 * 1000;
      a.controlPlayer(a.player, a.dummy, 0.05);
      out.bufferIsCheckedAtRecoveryBoundaryBeforeFrameEnd = !a.player.grounded && a.player.vy < 0;
      setup('roundhouse');
      a.player.atk.t = endTime(a.player) - 0.1;
      a.queueAction('jump');
      a.queueAction('kick');
      a.controlPlayer(a.player, a.dummy, 0.1);
      out.jumpAndAttackResolveTogetherAsAerial = !a.player.grounded && a.player.atk?.key === 'jkick';
      setup();
      a.input.up = 1;
      a.queueAction('kick');
      out.heldUpKickStartsAerialImmediately = !a.player.grounded && a.player.atk?.key === 'jkick' && a.player.atk.t === 0;
      setup('roundhouse');
      a.player.atk.t = endTime(a.player) - 0.12;
      a.input.block = a.input.down = 1;
      a.controlPlayer(a.player, a.dummy, 0.12);
      out.downGuardResumesAtRecoveryEnd = a.player.state === 'block' && a.player.crouching && a.hurtbox(a.player).h < 80;
      setup('roundhouse');
      a.player.atk.t = endTime(a.player) - 0.1;
      a.input.down = a.input.right = 1;
      a.queueAction('kick');
      a.input.down = a.input.right = 0;
      a.controlPlayer(a.player, a.dummy, 0.1);
      out.bufferPreservesDirectionalSlide = a.player.atk?.key === 'slide';
      setup('roundhouse');
      a.player.atk.t = endTime(a.player) - 0.1;
      a.player.meter = 100;
      a.input.down = 1;
      a.queueAction('nitro');
      a.input.down = 0;
      a.controlPlayer(a.player, a.dummy, 0.1);
      out.bufferPreservesLowNitro = a.player.atk?.key === 'nitrokick' && a.player.atk.low;
      setup('roundhouse');
      a.player.atk.t = endTime(a.player) - 0.1;
      a.queueAction('punch');
      a.queueAction('special');
      a.queueAction('kick');
      a.controlPlayer(a.player, a.dummy, 0.1);
      out.latestAttackReplacesOlderRequests = a.player.atk?.key === 'roundhouse' && !a.pressBuf.punch && !a.pressBuf.special;
      const distances = [];
      for (const attacking of [false, true]) {
        setup();
        a.player.grounded = false;
        a.player.y -= 70;
        a.input.left = 1;
        if (attacking) a.startAttack(a.player, 'jkick');
        a.controlPlayer(a.player, a.dummy, 0.1);
        distances.push(160 - a.player.x);
      }
      out.airAttackRetainsSteering = distances.every(d => Math.abs(d - 8.8) < 0.001);
      setup();
      a.player.grounded = false;
      a.player.y -= 100;
      a.player.meter = 100;
      a.input.right = 1;
      a.startAttack(a.player, 'nitrokick');
      a.controlPlayer(a.player, a.dummy, 0.48);
      out.airNitroDoesNotStackSteering = Math.abs(a.player.x - 160 - 105.6) < 0.001;
      setup('roundhouse');
      a.queueAction('jump');
      a.controlPlayer(a.player, a.dummy, 0.44);
      out.expiredEarlyTapDoesNotJumpMuchLater = a.player.grounded && !a.pressBuf.jump;
      setup('roundhouse');
      a.player.atk.t = endTime(a.player) - 0.1;
      a.game.hitStop = 0.3;
      a.queueAction('jump');
      const time = a.game.inputTime;
      a.update(0.3);
      out.hitStopDoesNotAgeCommands = a.game.inputTime === time && !!a.pressBuf.jump && a.player.grounded;
      a.controlPlayer(a.player, a.dummy, 0.1);
      out.bufferExecutesAfterHitStop = !a.player.grounded;
      setup();
      a.player.hitstun = 0.1;
      a.player.state = 'hurt';
      a.input.left = 1;
      a.controlPlayer(a.player, a.dummy, 0.12);
      out.hitstunStillCommitsThenResumesMovement = !a.player.hitstun && a.player.state === 'walk' && a.player.x < 160;
      setup('roundhouse');
      a.queueAction('jump');
      a.pauseGame();
      out.pauseClearsHeldAndBufferedInputs = !Object.values(a.input).some(Boolean) && !Object.values(a.pressBuf).some(Boolean);
    } finally {
      a.Sfx.play = play;
      a.resetInput();
      a.game.paused = true;
    }
    return out;
  });
  for (const [name, passed] of Object.entries(results)) check(passed, 'Input: ' + name);

  // The real keyboard path reproduces the reported Kick → A sequence.
  await page.evaluate(() => {
    INJ.resumeGame();
    INJ.game.round = 0; INJ.resetRound(); INJ.game.state = 'fight';
    INJ.dummy.aiT = 999; INJ.player.x = 180; INJ.dummy.x = 380;
  });
  await page.keyboard.down('k');
  await page.keyboard.down('a');
  check(await page.evaluate(() => INJ.input.left === 1), 'Input: keyboard direction remains held during Kick');
  await page.waitForFunction(() => !INJ.player.atk && INJ.player.x < 178);
  check(await page.evaluate(() => INJ.player.state === 'walk'), 'Input: real Kick then A walks as soon as recovery completes');
  await page.keyboard.up('k');
  check(await page.evaluate(() => INJ.input.left === 1), 'Input: releasing attack preserves the held movement key');
  await page.keyboard.up('a');
  await page.evaluate(() => { INJ.game.hitStop = 999; INJ.resetInput(); });
  await page.keyboard.down('a');
  await page.keyboard.down('d');
  check(await page.evaluate(() => !INJ.input.left && !INJ.input.right), 'Input: opposite horizontal keys resolve to neutral');
  await page.keyboard.up('d');
  check(await page.evaluate(() => INJ.input.left === 1), 'Input: releasing one opposite restores the other held direction');
  await page.keyboard.up('a');
  await page.keyboard.down('s');
  await page.keyboard.down('w');
  check(await page.evaluate(() => !INJ.input.up && !INJ.input.down && !INJ.pressBuf.jump), 'Input: opposite vertical keys cannot create a ghost jump');
  await page.keyboard.up('s');
  await page.keyboard.up('w');
  await page.keyboard.down('Space');
  check(await page.evaluate(() => INJ.input.up === 1), 'Input: Space behaves as a held jump direction');
  await page.keyboard.up('Space');
  check(await page.evaluate(() => !INJ.input.up && INJ.pressBuf.jump > INJ.game.inputTime), 'Input: releasing Space preserves a short jump request');
  await page.waitForTimeout(260);
  check(await page.evaluate(() => !!INJ.consume('jump')), 'Input: wall time during hit-stop cannot expire a buffered jump');
  await page.evaluate(() => {
    INJ.resetInput(); INJ.startAttack(INJ.player, 'roundhouse');
    INJ.player.atk.t = 0.33;
  });
  const cdp = await page.context().newCDPSession(page);
  const zone = await page.locator('#stickZone').boundingBox();
  const kick = await page.locator('[data-act="kick"]').boundingBox();
  const point = (id, x, y) => ({ id, x, y, radiusX: 5, radiusY: 5, force: 1 });
  let left = point(11, zone.x + zone.width / 2, zone.y + zone.height / 2);
  const right = point(12, kick.x + kick.width / 2, kick.y + kick.height / 2);
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [left] });
  left = { ...left, x: left.x + 24, y: left.y - 38 };
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [left] });
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [left, right] });
  check(await page.evaluate(() => INJ.input.up === 1 && INJ.input.right === 1 && !!INJ.pressBuf.kick), 'Input: real two-thumb diagonal jump and Kick coexist during recovery');
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [right] });
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] });
  check(await page.evaluate(() => {
    INJ.controlPlayer(INJ.player, INJ.dummy, 0.1);
    return !INJ.player.grounded && INJ.player.atk?.key === 'jkick' && INJ.player.vx > 0;
  }), 'Input: released touch chord buffers a diagonal aerial kick');
  await cdp.detach();
  await page.evaluate(() => { INJ.resetInput(); INJ.game.paused = true; });
};
